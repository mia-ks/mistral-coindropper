import json

d = json.load(open('dump/levels_final.json'))
vis = json.load(open('dump/level_visual.json'))
out = {'scale': d['scale'], 'coins': d['coins'], 'levels': {}}
for nm, s in d['levels'].items():
    lvl = {
        'goal': s.get('goal'),
        'camera': s.get('camera'),
        'spawn': s.get('spawn'),
        'collector': s.get('collector'),
        'tiers': [],
        'machines': s.get('machines', []),
    }
    v = vis.get(nm, {})
    for t in s.get('tiers', []):
        tv = v.get('tiers', {}).get(t['name'], {}).get('visual') or t.get('visual')
        lvl['tiers'].append({
            'name': t['name'], 'pos': t['pos'], 'yaw': t['yaw'],
            'floor': t['floor'], 'visual': tv,
            'pusher': t.get('pusher'),
        })
    if v.get('bg'):
        lvl['bg'] = v['bg']
    vms = v.get('machines', [])
    for m in lvl['machines']:
        for vm in vms:
            if vm['go'] == m['go']:
                m['visual'] = vm.get('visual')
    out['levels'][nm] = lvl

header = """// GENERATED by re/gen_js.py from re/dump/levels_final.json
// (Unity level prefab hierarchies with parent-resolved WORLD transforms, collider AABBs,
//  per-instance interaction params, LevelCameraBounds camera rig). Do not edit by hand.
"""
body = 'const LEVEL_LAYOUTS = ' + json.dumps(out, indent=1) + ';\n'
body += "if (typeof module !== 'undefined' && module.exports) module.exports = { LEVEL_LAYOUTS };\n"
open('/workspace/coindozer-clean/js/level_layouts.js', 'w').write(header + body)
print('wrote js/level_layouts.js', len(body), 'bytes')

